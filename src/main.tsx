createRoot(document.getElementById('root')!).render(<React.StrictMode><QueryClientProvider client={client}><ThemeProvider theme={smartAquaTheme}><CssBaseline/><BrowserRouter><App/></BrowserRouter></ThemeProvider></QueryClientProvider></React.StrictMode>);
